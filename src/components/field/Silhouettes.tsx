import type { ReactElement } from 'react';
import { toSvg, type Pt } from './geometry';
import { limb } from './limb';

/**
 * 场上人物的剪影。
 *
 * 球场是俯视图，人却按**立面**画 —— 这是场地图解的通行画法，
 * 因为俯视的人只是一个点，读者就失去了唯一的比例参照。
 * 既然它是全图的比例尺，形体就必须是真的：按 1.88 m 的身高建立，
 * 关节位置取常用的人体比例（肩 0.82H、髋 0.53H、膝 0.28H）。
 *
 * 形体不写死成一长串 path 字符串，而是给出关节点，由 limb() 生成有粗细变化的肢体 ——
 * 这样调姿势只要挪几个数，不用重算贝塞尔。
 *
 * 只画纯色块面：不出现任何球队、联盟的标志、吉祥物或真实球员的形象。
 */

export type Posture = 'batter' | 'catcher' | 'pitcher' | 'runner';

/** 单位是米，脚踩在原点，往上是负 y（SVG 坐标） */
const p = (x: number, y: number): Pt => ({ x, y });

interface Figure {
  head: { cx: number; cy: number; rx: number; ry: number };
  /** [起点, 终点, 起点宽, 终点宽] */
  limbs: [Pt, Pt, number, number][];
  /** 手套、球棒之类的附件 */
  extras?: ReactElement;
  /** 脚下投影的半宽 */
  shade: number;
}

/**
 * 右打者的架式：重心后坐，前脚跨出，双手收在后肩，球棒指向斜后上方。
 * 站在三垒侧的打击区里，面朝本垒（+x）。
 */
